'use strict';

const lib = require('./index.js');
const {version} = require('../package.json');

// Self-contained draft-07 schema (for SchemaStore, IDEs)
// rewrites 'defs#/name' references into '#/definitions/name'
const rewrite = obj => JSON.parse(
  JSON.stringify(obj).replace(/"defs#\//g, '"#/definitions/')
);

const definitions = rewrite(lib.defs);
delete definitions.$id;

module.exports = {
  $schema: 'http://json-schema.org/draft-07/schema#',
  $id: 'https://wavedrom.com/schema/wavedrom.json',
  $comment: 'Generated by wavedrom-schema v' + version + ' https://github.com/wavedrom/schema',
  title: 'WaveDrom',
  description: 'WaveJSON: WaveDrom timing diagram, bit-field (register), or logic circuit description\nhttps://wavedrom.com',
  definitions,
  ...rewrite(lib.any)
};
